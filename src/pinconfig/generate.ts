/**
 * Pin setup tool: turns a table of pin settings into register-level C, the way
 * a vendor configurator generates its GPIO init function. Pure text in, text
 * out, so it runs in the UI and in the tests.
 */
import { AF_TABLE } from '../emu/peripherals/gpio';

export type PinMode = 'input' | 'output' | 'af' | 'analog';
export type PinPull = 'none' | 'up' | 'down';

export interface PinConfig {
  /** "PA5" */
  pin: string;
  mode: PinMode;
  pull: PinPull;
  /** Output and alternate-function pins only. */
  openDrain: boolean;
  /** Alternate-function number 0..7 (mode "af"). */
  af: number;
  /** Level an output pin starts at. */
  startHigh: boolean;
  /** What is connected, for the comment in the generated code. */
  note?: string;
}

export const PORTS = ['A', 'B', 'C'] as const;

/** PA13 and PA14 carry the debugger connection (SWDIO / SWCLK). */
export const DEBUG_PINS = ['PA13', 'PA14'];

export function parsePin(pin: string): { port: string; n: number } {
  const m = /^P([A-F])(\d{1,2})$/.exec(pin);
  if (!m || Number(m[2]) > 15) throw new Error(`Not a pin name: ${pin}`);
  return { port: m[1], n: Number(m[2]) };
}

export function defaultConfig(pin: string, note?: string): PinConfig {
  const afs = Object.keys(AF_TABLE[pin] ?? {});
  return { pin, mode: 'output', pull: 'none', openDrain: false, af: afs.length ? Number(afs[0]) : 0, startHigh: false, note };
}

/** Alternate functions of a pin that the simulator models: [number, signal name]. */
export function functionsOf(pin: string): Array<[number, string]> {
  return Object.entries(AF_TABLE[pin] ?? {}).map(([n, signal]) => [Number(n), signal]);
}

/** One line of plain language for a setting, used as the comment and in the summary. */
export function describe(c: PinConfig): string {
  const pull = c.pull === 'up' ? ' with pull-up' : c.pull === 'down' ? ' with pull-down' : '';
  switch (c.mode) {
    case 'input':
      return `input${pull || ', no pull resistor'}`;
    case 'output':
      return `output, ${c.openDrain ? 'open-drain' : 'push-pull'}${pull}, starts ${c.startHigh ? 'high' : 'low'}`;
    case 'af': {
      const signal = AF_TABLE[c.pin]?.[c.af];
      return `alternate function ${c.af}${signal ? ` = ${signal}` : ''}, ${c.openDrain ? 'open-drain' : 'push-pull'}${pull}`;
    }
    case 'analog':
      return 'analog (for the ADC)';
  }
}

export const BEGIN_MARK = '/* ---- pin setup: generated by the Pin setup tool ---- */';
export const END_MARK = '/* ---- end of pin setup ---- */';

function sortPins(configs: PinConfig[]): PinConfig[] {
  return [...configs].sort((a, b) => {
    const pa = parsePin(a.pin);
    const pb = parsePin(b.pin);
    return pa.port === pb.port ? pa.n - pb.n : pa.port < pb.port ? -1 : 1;
  });
}

/** The statements that configure one pin, in the order they must run. */
function pinStatements(c: PinConfig): string[] {
  const { port, n } = parsePin(c.pin);
  const g = `GPIO${port}`;
  const moder = `GPIO_MODER_MODER${n}`;
  const pupdr = `GPIO_PUPDR_PUPDR${n}`;
  const out: string[] = [];

  if (c.mode === 'analog') {
    // analog is 11: both bits set, nothing to clear first
    out.push(`${g}->MODER |= ${moder};`);
    out.push(`${g}->PUPDR &= ~${pupdr};`);
    return out;
  }

  if (c.mode === 'output') {
    // level first, so the pin does not glitch to the wrong level when it becomes an output
    out.push(`${g}->BSRR = 1u << ${c.startHigh ? n : `(${n} + 16)`};`);
  }
  if (c.mode === 'output' || c.mode === 'af') {
    out.push(c.openDrain ? `${g}->OTYPER |= GPIO_OTYPER_OT_${n};` : `${g}->OTYPER &= ~GPIO_OTYPER_OT_${n};`);
  }
  if (c.mode === 'af') {
    const idx = n < 8 ? 0 : 1;
    const shift = (n % 8) * 4;
    out.push(`${g}->AFR[${idx}] = (${g}->AFR[${idx}] & ~(0xFu << ${shift})) | (${c.af}u << ${shift});`);
  }
  out.push(c.pull === 'none' ? `${g}->PUPDR &= ~${pupdr};` : `${g}->PUPDR = (${g}->PUPDR & ~${pupdr}) | ${pupdr}_${c.pull === 'up' ? 0 : 1};`);
  out.push(
    c.mode === 'input' ? `${g}->MODER &= ~${moder};` : `${g}->MODER = (${g}->MODER & ~${moder}) | ${moder}_${c.mode === 'output' ? 0 : 1};`,
  );
  return out;
}

/** The complete generated block: markers, then `static void pins_init(void)`. */
export function generate(configs: PinConfig[]): string {
  const pins = sortPins(configs);
  const ports = [...new Set(pins.map((c) => parsePin(c.pin).port))];
  const lines: string[] = [BEGIN_MARK, 'static void pins_init(void)', '{'];
  if (pins.length === 0) {
    lines.push('    /* no pins configured yet */');
  } else {
    lines.push('    /* A port ignores every write until its clock is switched on. */');
    lines.push(`    RCC->AHBENR |= ${ports.map((p) => `RCC_AHBENR_GPIO${p}EN`).join(' | ')};`);
    for (const c of pins) {
      lines.push('');
      lines.push(`    /* ${c.pin}: ${describe(c)}${c.note ? ` (${c.note})` : ''} */`);
      for (const s of pinStatements(c)) lines.push(`    ${s}`);
    }
  }
  lines.push('}', END_MARK);
  return lines.join('\n');
}

/** What the generated code does and why, as short notes shown under it. */
export function notes(configs: PinConfig[]): string[] {
  const out: string[] = [];
  if (configs.length === 0) return out;
  out.push('The clock enable in `RCC->AHBENR` comes first. Without it the port ignores every other line.');
  out.push('Every register is changed with clear-then-set on the bits of one pin, so pins that are not listed keep their configuration.');
  if (configs.some((c) => c.mode === 'output')) {
    out.push('For outputs the start level is written to `BSRR` before the pin is switched to output mode, so it never drives the wrong level, not even for a moment.');
  }
  if (configs.some((c) => c.mode === 'af')) {
    out.push(
      'An alternate function only connects the pin to a peripheral. The peripheral itself (timer, USART, I2C, SPI) still needs its own clock enable and configuration.',
    );
  }
  if (configs.some((c) => c.mode === 'af' && c.openDrain)) out.push('Open-drain pins can only pull low. They need a pull-up resistor, as on an I2C bus.');
  if (configs.some((c) => c.mode === 'input' && c.pull === 'none')) {
    out.push('An input without a pull resistor floats when nothing drives it. That is fine if the board has an external resistor, as the on-board button has.');
  }
  if (configs.some((c) => c.mode === 'analog')) out.push('Analog mode disconnects the digital input buffer. The ADC still needs to be enabled and the channel selected.');
  if (configs.some((c) => DEBUG_PINS.includes(c.pin))) {
    out.push('PA13 and PA14 are the debug pins. Reconfiguring them cuts the debugger connection on a real board.');
  }
  return out;
}

/**
 * Put the generated block into a source file. An earlier generated block is
 * replaced; otherwise the block goes in front of main() and a call to
 * pins_init() is added as the first statement of main().
 */
export function applyToSource(source: string, block: string): string {
  const nl = source.includes('\r\n') ? '\r\n' : '\n';
  const text = block.split('\n').join(nl);
  const begin = source.indexOf(BEGIN_MARK);
  const end = source.indexOf(END_MARK);
  let out: string;
  if (begin >= 0 && end > begin) {
    out = source.slice(0, begin) + text + source.slice(end + END_MARK.length);
  } else {
    const main = /^[ \t]*int\s+main\s*\(/m.exec(source);
    if (main) out = source.slice(0, main.index) + text + nl + nl + source.slice(main.index);
    else {
      // no main() in this file: after the last #include, or at the top
      const includes = [...source.matchAll(/^[ \t]*#include[^\n]*\n/gm)];
      const at = includes.length ? includes[includes.length - 1].index + includes[includes.length - 1][0].length : 0;
      out = source.slice(0, at) + nl + text + nl + source.slice(at);
    }
  }
  if (!/\bpins_init\s*\(\s*\)\s*;/.test(out)) {
    const body = /^([ \t]*)int\s+main\s*\([^)]*\)\s*\{[ \t]*\r?\n/m.exec(out);
    if (body) {
      const at = body.index + body[0].length;
      out = out.slice(0, at) + `${body[1]}    pins_init();${nl}` + out.slice(at);
    }
  }
  return out;
}
